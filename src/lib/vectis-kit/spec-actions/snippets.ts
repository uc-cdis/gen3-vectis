/**
 * "Use this query elsewhere": the Python, curl and GraphQL renderings of a QuerySpec. Each is built from the validated
 * spec only (validate.ts), never from page text, and every value is escaped for its target language here. Credentials
 * are never included: the snippets authenticate the way the user's own tooling does (Gen3Auth, their own token).
 */
import type { FilterClause, QuerySpec } from '../spec';
import { SpecError, cleanSpec, rowsBody } from './validate';

// ---------------------------------------------------------------- escaping
/**
 * Escaping for every language a spec is rendered into. User-controlled text (filter values, column names, window
 * strings) only ever reaches generated code through these functions. Each one produces a COMPLETE literal, so the
 * caller never concatenates raw text into a string.
 */

/** Characters JSON leaves bare but that other tools treat as line breaks or are invisible. */
const EXTRA_ESCAPES: Record<string, string> = { '\u2028': '\\u2028', '\u2029': '\\u2029', '\u007f': '\\u007f', '\u0085': '\\u0085' };

/** A double-quoted string literal valid in Python, JSON and JavaScript. Never contains a raw line break or quote. */
export function quoted(text: string): string {
  // JSON.stringify escapes quotes, backslashes and control characters, and writes lone surrogates as \udXXX.
  return JSON.stringify(text).replace(/[\u2028\u2029\u007f\u0085]/g, (c) => EXTRA_ESCAPES[c] as string);
}

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };

/** Render JSON-shaped data as a Python literal (None/True/False, double-quoted strings, trailing commas). */
export function pythonLiteral(value: unknown, indent = 0): string {
  const pad = '    '.repeat(indent);
  const inner = '    '.repeat(indent + 1);
  if (value === null || value === undefined) return 'None';
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('Only finite numbers can be written to code.');
    return String(value);
  }
  if (typeof value === 'string') return quoted(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${(value as Json[]).map((v) => `${inner}${pythonLiteral(v, indent + 1)},`).join('\n')}\n${pad}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, Json>);
    if (entries.length === 0) return '{}';
    return `{\n${entries.map(([k, v]) => `${inner}${quoted(k)}: ${pythonLiteral(v, indent + 1)},`).join('\n')}\n${pad}}`;
  }
  throw new Error('This value cannot be written to code.');
}

/** A GraphQL/JS-safe identifier check. Used for field and index names that appear unquoted in a query. */
const GRAPHQL_NAME = /^[_A-Za-z][_0-9A-Za-z]*$/;

const API_PATH = /^\/[A-Za-z0-9._~/-]{0,100}$/;
/** The API path under the commons URL, checked because it is written into a shell or Python line. */
function apiPathOf(opts: { apiPath?: string }): string {
  const apiPath = opts.apiPath ?? '/siem';
  if (!API_PATH.test(apiPath)) throw new Error('The API path is not valid.');
  return apiPath;
}
const clampInt = (value: number | undefined, fallback: number, min: number, max: number): number => Math.min(Math.max(Math.trunc(value ?? fallback), min), max);

// ---------------------------------------------------------------- curl
const DELIMITER = 'VECTIS_SPEC_JSON';

/**
 * A curl command for the spec. The token is a placeholder shell variable, never a value.
 *
 * The body goes in a heredoc whose delimiter is quoted, so the shell performs NO expansion inside it: quotes,
 * backticks, `$(...)` and `${...}` in a filter value stay literal. The only shell text outside the heredoc is fixed.
 */
export function toCurl(spec: QuerySpec, opts: { apiPath?: string; limit?: number } = {}): string {
  const apiPath = apiPathOf(opts);
  const limit = clampInt(opts.limit, 250, 1, 250);
  const body = JSON.stringify(rowsBody(spec, { limit, offset: 0 }), null, 2).replace(/[\u2028\u2029]/g, (c) => (c === '\u2028' ? '\\u2028' : '\\u2029'));
  if (body.split('\n').some((line) => line === DELIMITER)) throw new Error('The query cannot be written as a command.');
  return [
    '# Generated by the Vectis security console. No token is embedded.',
    '# Set VECTIS_URL (for example https://vectis.example.org) and VECTIS_TOKEN (a short-lived access token)',
    '# in your shell first. Do not paste a token into this command or into a shared file.',
    `curl --fail-with-body -sS -X POST "\${VECTIS_URL}${apiPath}/rows" \\`,
    '  -H "Authorization: Bearer ${VECTIS_TOKEN}" \\',
    '  -H "Content-Type: application/json" \\',
    `  --data-binary @- <<'${DELIMITER}'`,
    body,
    DELIMITER,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- GraphQL
interface GraphqlResult {
  /** The query document. Contains no user-controlled text except validated identifiers. */
  query: string;
  /** The variables pane content (JSON). Every filter value lives here, so it is escaped by JSON. */
  variables: string;
}

/** Guppy-style filter object for one clause. */
function guppyClause(c: FilterClause): Record<string, unknown> {
  switch (c.op) {
    case 'eq': return { '=': { [c.field]: c.value } };
    case 'neq': return { '!=': { [c.field]: c.value } };
    case 'in': return { IN: { [c.field]: c.value } };
    case 'gte': return { '>=': { [c.field]: c.value } };
    case 'lte': return { '<=': { [c.field]: c.value } };
    case 'contains': return { search: { keyword: c.value, fields: [c.field] } };
  }
}

/**
 * A GraphQL query for the Query page (the "Flat" endpoint, Guppy dialect). Filters, sort and the time window are
 * passed as JSON VARIABLES, never spliced into the query text. Only index and column names appear in the text, and
 * those are validated identifiers.
 *
 * `timeField` is required: without it the time window could not be expressed and the query would silently widen.
 */
export function toGraphql(spec: QuerySpec, timeField: string, opts: { first?: number } = {}): GraphqlResult {
  const s = cleanSpec(spec);
  if (!GRAPHQL_NAME.test(timeField)) throw new SpecError('The time field is not valid.');
  const columns = s.columns ?? [];
  if (columns.length === 0) throw new SpecError('Choose at least one column to write a GraphQL query.');
  for (const name of [s.index_name, ...columns]) if (!GRAPHQL_NAME.test(name)) throw new SpecError('A name is not valid in GraphQL.');
  const first = Math.min(Math.max(Math.trunc(opts.first ?? 250), 1), 250);

  const clauses: Record<string, unknown>[] = [
    { '>=': { [timeField]: s.window.start } },
    { '<=': { [timeField]: s.window.end } },
    ...(s.filters ?? []).map(guppyClause),
  ];
  const variables: Record<string, unknown> = { filter: { AND: clauses } };
  if (s.sort) variables.sort = [{ [s.sort.field]: s.sort.dir ?? 'desc' }];

  const args = `filter: $filter, first: ${first}, offset: 0${s.sort ? ', sort: $sort' : ''}`;
  const decl = `$filter: JSON${s.sort ? ', $sort: JSON' : ''}`;
  const query = [
    `query VectisRows(${decl}) {`,
    `  ${s.index_name}(${args}) {`,
    ...columns.map((c) => `    ${c}`),
    '  }',
    '}',
    '',
  ].join('\n');
  return { query, variables: JSON.stringify(variables, null, 2) };
}

// ---------------------------------------------------------------- Python
interface PythonOptions {
  /** Path of the SIEM API under the commons URL. */
  apiPath?: string;
  pageSize?: number;
  maxPages?: number;
}

/**
 * Python (requests + pandas) that runs the spec against the Vectis API.
 *
 * No credential is embedded. `Gen3Auth()` from the gen3 SDK reads the workspace's own login (or the user's local gen3
 * credentials file). The only user-controlled text is inside `request`, written by `pythonLiteral`, which escapes it.
 */
export function toPython(spec: QuerySpec, opts: PythonOptions = {}): string {
  const apiPath = apiPathOf(opts);
  const pageSize = clampInt(opts.pageSize, 250, 1, 250);
  const maxPages = clampInt(opts.maxPages, 20, 1, 1000);
  const request = rowsBody(spec);
  return [
    '# Generated by the Vectis security console.',
    '# No credentials are embedded: Gen3Auth() uses the login of the Vectis workspace this runs in,',
    '# or your local gen3 credentials file.',
    'import pandas as pd',
    'import requests',
    'from gen3.auth import Gen3Auth',
    '',
    `PAGE_SIZE = ${pageSize}`,
    `MAX_PAGES = ${maxPages}  # a safety limit, raise it if you need more rows`,
    '',
    'auth = Gen3Auth()',
    `request = ${pythonLiteral(request)}`,
    '',
    'rows = []',
    'for page in range(MAX_PAGES):',
    '    body = {**request, "paging": {"limit": PAGE_SIZE, "offset": page * PAGE_SIZE}}',
    `    resp = requests.post(f"{auth.endpoint}${apiPath}/rows", json=body, auth=auth, timeout=60)`,
    '    resp.raise_for_status()',
    '    batch = resp.json()["rows"]',
    '    rows.extend(batch)',
    '    if len(batch) < PAGE_SIZE:',
    '        break',
    '',
    'df = pd.DataFrame(rows)',
    'df.head()',
    '',
  ].join('\n');
}
