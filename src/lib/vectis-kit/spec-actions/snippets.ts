/**
 * "Use this query elsewhere": the Python, curl and GraphQL renderings of a QuerySpec. Each is built from the validated
 * spec only (validate.ts), never from page text, and every value is escaped for its target language here. Credentials
 * are never included: the snippets authenticate the way the user's own tooling does (Gen3Auth, their own token).
 */
import type { FilterClause, QuerySpec } from '../spec';
import { SpecError, cleanSpec, rowsBody } from './validate';

// ---------------------------------------------------------------- escaping
/**
 * Escaping for every language a spec is rendered into. User-controlled text (filter values, column names, window
 * strings) only ever reaches generated code through these functions. Each one produces a COMPLETE literal, so the
 * caller never concatenates raw text into a string.
 */

/** Characters JSON leaves bare but that other tools treat as line breaks or are invisible. */
const EXTRA_ESCAPES: Record<string, string> = { '\u2028': '\\u2028', '\u2029': '\\u2029', '\u007f': '\\u007f', '\u0085': '\\u0085' };

/** A double-quoted string literal valid in Python, JSON and JavaScript. Never contains a raw line break or quote. */
export function quoted(text: string): string {
  // JSON.stringify escapes quotes, backslashes and control characters, and writes lone surrogates as \udXXX.
  return JSON.stringify(text).replace(/[\u2028\u2029\u007f\u0085]/g, (c) => EXTRA_ESCAPES[c] as string);
}

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };

/** Render JSON-shaped data as a Python literal (None/True/False, double-quoted strings, trailing commas). */
export function pythonLiteral(value: unknown, indent = 0): string {
  const pad = '    '.repeat(indent);
  const inner = '    '.repeat(indent + 1);
  if (value === null || value === undefined) return 'None';
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('Only finite numbers can be written to code.');
    return String(value);
  }
  if (typeof value === 'string') return quoted(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${(value as Json[]).map((v) => `${inner}${pythonLiteral(v, indent + 1)},`).join('\n')}\n${pad}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, Json>);
    if (entries.length === 0) return '{}';
    return `{\n${entries.map(([k, v]) => `${inner}${quoted(k)}: ${pythonLiteral(v, indent + 1)},`).join('\n')}\n${pad}}`;
  }
  throw new Error('This value cannot be written to code.');
}

/** A GraphQL/JS-safe identifier check. Used for field and index names that appear unquoted in a query. */
const GRAPHQL_NAME = /^[_A-Za-z][_0-9A-Za-z]*$/;

/** "All events" is console-only; the gateway serves each underlying index, so generated code loops over them. */
export const ALL_EVENTS = 'all_events';
/** Gateway indexes behind "All events" (audit_event reads api_activity's events, so it is not listed twice). */
export const GATEWAY_INDEXES = ['http_activity', 'api_activity', 'authentication', 'network_activity'] as const;

const API_PATH = /^\/[A-Za-z0-9._~/-]{0,100}$/;
/** The GraphQL path under the commons URL. Validated because it is written into a shell or Python line. */
export const GUPPY_PATH = '/guppy/graphql';
function apiPathOf(opts: { apiPath?: string }): string {
  const apiPath = opts.apiPath ?? GUPPY_PATH;
  if (!API_PATH.test(apiPath)) throw new Error('The API path is not valid.');
  return apiPath;
}
const clampInt = (value: number | undefined, fallback: number, min: number, max: number): number => Math.min(Math.max(Math.trunc(value ?? fallback), min), max);

// ---------------------------------------------------------------- curl
const DELIMITER = 'VECTIS_SPEC_JSON';

/**
 * A curl command for the spec. The token is a placeholder shell variable. The service ignores sort, so it is applied after the response.
 * The body is in a quoted heredoc, so the shell expands nothing in it; the shell text outside it is fixed.
 */
export function toCurl(spec: QuerySpec, opts: { apiPath?: string; limit?: number; timeField: string }): string {
  const apiPath = apiPathOf(opts);
  const limit = clampInt(opts.limit, 250, 1, 250);
  const g = toGraphql(spec, opts.timeField, { first: limit, offset: 0 });
  const body = JSON.stringify({ query: g.query, variables: JSON.parse(g.variables) }, null, 2).replace(/[\u2028\u2029]/g, (c) => (c === '\u2028' ? '\\u2028' : '\\u2029'));
  if (body.split('\n').some((line) => line === DELIMITER)) throw new Error('The query cannot be written as a command.');
  return [
    '# Generated by the Vectis security console. No token is embedded.',
    '# Set VECTIS_URL (for example https://vectis.example.org) and VECTIS_TOKEN (a short-lived access token)',
    '# in your shell first. Do not paste a token into this command or into a shared file.',
    '# The service returns every column of the index and orders rows itself: pick columns and sort afterwards.',
    `curl --fail-with-body -sS -X POST "\${VECTIS_URL}${apiPath}" \\`,
    '  -H "Authorization: Bearer ${VECTIS_TOKEN}" \\',
    '  -H "Content-Type: application/json" \\',
    `  --data-binary @- <<'${DELIMITER}'`,
    body,
    DELIMITER,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- GraphQL
interface GraphqlResult {
  /** The query document. Contains no user-controlled text except validated identifiers. */
  query: string;
  /** The variables pane content (JSON). Every filter value lives here, so it is escaped by JSON. */
  variables: string;
}

/** Guppy-style filter object for one clause. */
export function guppyClause(c: FilterClause): Record<string, unknown> {
  switch (c.op) {
    case 'eq': return { '=': { [c.field]: c.value } };
    case 'neq': return { '!=': { [c.field]: c.value } };
    case 'in': return { IN: { [c.field]: c.value } };
    case 'gte': return { '>=': { [c.field]: c.value } };
    case 'lte': return { '<=': { [c.field]: c.value } };
    // SEARCH is {field: text}, matched case-insensitively anywhere in the value.
    case 'contains': return { search: { [c.field]: c.value } };
  }
}

/**
 * A GraphQL query for the Query page (the "Flat" endpoint, Guppy dialect). Filters, sort and the time window are
 * passed as JSON VARIABLES, never spliced into the query text. Only index and column names appear in the text, and
 * those are validated identifiers.
 *
 * `timeField` is required: without it the time window could not be expressed and the query would silently widen.
 */
export function toGraphql(spec: QuerySpec, timeField: string, opts: { first?: number; offset?: number } = {}): GraphqlResult {
  const s = cleanSpec(spec);
  if (s.index_name === ALL_EVENTS) throw new SpecError('"All events" is not one index at the gateway. Choose a single index to write a GraphQL query or curl command; the Python export covers all of them.');
  if (!GRAPHQL_NAME.test(timeField)) throw new SpecError('The time field is not valid.');
  const columns = s.columns ?? [];
  if (columns.length === 0) throw new SpecError('Choose at least one column to write a GraphQL query.');
  for (const name of [s.index_name, ...columns]) if (!GRAPHQL_NAME.test(name)) throw new SpecError('A name is not valid in GraphQL.');
  const first = Math.min(Math.max(Math.trunc(opts.first ?? 250), 1), 250);

  const clauses: Record<string, unknown>[] = [
    { '>=': { [timeField]: s.window.start } },
    { '<=': { [timeField]: s.window.end } },
    ...(s.filters ?? []).map(guppyClause),
  ];
  const variables: Record<string, unknown> = { filter: { AND: clauses } };
  if (s.sort) variables.sort = [{ [s.sort.field]: s.sort.dir ?? 'desc' }];

  const offset = Math.min(Math.max(Math.trunc(opts.offset ?? 0), 0), 1_000_000);
  const args = `filter: $filter, first: ${first}, offset: ${offset}${s.sort ? ', sort: $sort' : ''}`;
  const decl = `$filter: JSON${s.sort ? ', $sort: JSON' : ''}`;
  const query = [
    `query VectisRows(${decl}) {`,
    `  ${s.index_name}(${args}) {`,
    ...columns.map((c) => `    ${c}`),
    '  }',
    '}',
    '',
  ].join('\n');
  return { query, variables: JSON.stringify(variables, null, 2) };
}

// ---------------------------------------------------------------- Python
interface PythonOptions {
  /** Path of the GraphQL endpoint under the commons URL. */
  apiPath?: string;
  /** The commons URL the code talks to (the page's origin). */
  endpoint?: string;
  /** The index's time field, used to express the window as filters. */
  timeField: string;
  pageSize?: number;
  maxPages?: number;
}

const ENDPOINT_URL = /^(https:\/\/[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?(:\d{1,5})?|http:\/\/localhost(:\d{1,5})?)$/;
const PLACEHOLDER_ENDPOINT = 'https://your-vectis-host';
function endpointOf(opts: { endpoint?: string }): string {
  const e = opts.endpoint ?? PLACEHOLDER_ENDPOINT;
  if (!ENDPOINT_URL.test(e)) throw new Error('The commons URL is not valid.');
  return e;
}

/**
 * Python (requests + pandas) that runs the spec against the gateway's GraphQL endpoint, for a Jupyter cell.
 * The service returns every column and orders rows itself, so the code picks columns and sorts. An empty result prints
 * a hint because the service also answers a bad filter or an unsigned request that way.
 * No credential is embedded: a workspace uses Gen3Auth, elsewhere VECTIS_TOKEN is sent as a bearer token. User text goes
 * through `pythonLiteral`.
 */
export function toPython(spec: QuerySpec, opts: PythonOptions): string {
  const apiPath = apiPathOf(opts);
  const endpoint = endpointOf(opts);
  const pageSize = clampInt(opts.pageSize, 1000, 1, 5000);
  const maxPages = clampInt(opts.maxPages, 20, 1, 1000);
  const s = cleanSpec(spec);
  if (s.index_name === ALL_EVENTS) return toPythonAllEvents(s, { apiPath, endpoint, pageSize, maxPages, timeField: opts.timeField });
  const g = toGraphql(s, opts.timeField, { first: pageSize }); // validates names and builds the filter
  const filter = (JSON.parse(g.variables) as { filter: unknown }).filter;
  const columns = s.columns ?? [];
  const sortField = s.sort?.field ?? null;
  const sortAsc = (s.sort?.dir ?? 'desc') === 'asc';
  return [
    '# Generated by the Vectis security console.',
    '# No credentials are embedded.',
    '#  - In a Vectis workspace this runs as is: Gen3Auth uses the workspace\'s own login.',
    '#  - Anywhere else, set VECTIS_TOKEN to a short-lived access token first (os.environ["VECTIS_TOKEN"] = ...).',
    'import os',
    'import pandas as pd',
    'import requests',
    '',
    `ENDPOINT = ${quoted(endpoint)}`,
    `INDEX = ${quoted(s.index_name)}`,
    `COLUMNS = ${pythonLiteral(columns)}`,
    `SORT_FIELD, SORT_ASCENDING = ${sortField === null ? 'None' : quoted(sortField)}, ${sortAsc ? 'True' : 'False'}`,
    `PAGE_SIZE = ${pageSize}`,
    `MAX_PAGES = ${maxPages}  # a safety limit, raise it if you need more rows`,
    '',
    '# The time window and your filters, in the Guppy filter format the service reads.',
    `FILTER = ${pythonLiteral(filter)}`,
    '',
    'token = os.environ.get("VECTIS_TOKEN")',
    'if token:',
    '    auth, headers = None, {"Authorization": f"Bearer {token}"}',
    'else:',
    '    from gen3.auth import Gen3Auth',
    '    auth, headers = Gen3Auth(endpoint=ENDPOINT), {}',
    '',
    'def page_query(offset):',
    '    fields = " ".join(COLUMNS)',
    '    return f"query ($filter: JSON) {{ {INDEX}(filter: $filter, first: {PAGE_SIZE}, offset: {offset}) {{ {fields} }} }}"',
    '',
    'rows = []',
    'for page in range(MAX_PAGES):',
    '    body = {"query": page_query(page * PAGE_SIZE), "variables": {"filter": FILTER}}',
    `    resp = requests.post(f"{ENDPOINT}${apiPath}", json=body, headers=headers, auth=auth, timeout=120)`,
    '    resp.raise_for_status()',
    '    payload = resp.json()',
    '    if payload.get("errors"):',
    '        raise RuntimeError(payload["errors"])',
    '    batch = (payload.get("data") or {}).get(INDEX) or []',
    '    rows.extend(batch)',
    '    if len(batch) < PAGE_SIZE:',
    '        break',
    '',
    'if not rows:',
    '    print("No rows came back. Check you are signed in, that the window has data, and the column and filter names.")',
    'df = pd.DataFrame(rows)',
    'missing = [c for c in COLUMNS if c not in df.columns]',
    'if rows and missing:',
    '    print("Columns the service did not return:", missing)',
    'df = df[[c for c in COLUMNS if c in df.columns]]  # the service returns every column; keep the ones you chose',
    'if SORT_FIELD in df.columns:',
    '    df = df.sort_values(SORT_FIELD, ascending=SORT_ASCENDING).reset_index(drop=True)',
    'df.head()',
    '',
  ].join('\n');
}

/** Which gateway indexes an Index filter on All events keeps. Only eq, neq and in apply. */
function indexesFor(filters: readonly FilterClause[]): string[] {
  let keep: string[] = [...GATEWAY_INDEXES];
  for (const f of filters) {
    if (f.field !== 'index_name') continue;
    // audit_event is the same events as api_activity, so a filter that names it means api_activity.
    const named = (v: unknown) => (v === 'audit_event' ? 'api_activity' : String(v));
    if (f.op === 'eq') keep = keep.filter((i) => i === named(f.value));
    else if (f.op === 'neq') keep = keep.filter((i) => i !== named(f.value));
    else if (f.op === 'in' && Array.isArray(f.value)) { const want = new Set(f.value.map(named)); keep = keep.filter((i) => want.has(i)); }
    else throw new SpecError('An Index filter can be "is", "is not" or "is one of".');
  }
  if (keep.length === 0) throw new SpecError('No index is left after the Index filter.');
  return keep;
}

/** Runs the same query against each index behind "All events" and tags each row with its index. An Index filter picks which are asked. */
function toPythonAllEvents(s: QuerySpec, o: { apiPath: string; endpoint: string; pageSize: number; maxPages: number; timeField: string }): string {
  const indexes = indexesFor(s.filters ?? []);
  const wanted = s.columns ?? [];
  const columns = wanted.filter((c) => c !== 'index_name');
  if (columns.length === 0) throw new SpecError('Choose at least one column besides Index.');
  const rest = (s.filters ?? []).filter((f) => f.field !== 'index_name');
  const g = toGraphql({ ...s, index_name: indexes[0] as QuerySpec['index_name'], columns, filters: rest, sort: null }, o.timeField, { first: o.pageSize });
  const filter = (JSON.parse(g.variables) as { filter: unknown }).filter;
  const sortField = s.sort?.field ?? null;
  const sortAsc = (s.sort?.dir ?? 'desc') === 'asc';
  return [
    '# Generated by the Vectis security console.',
    '# "All events" is every index at once. The gateway serves each index separately, so this asks each one the same',
    '# question and adds an index_name column saying where every row came from.',
    '# No credentials are embedded.',
    '#  - In a Vectis workspace this runs as is: Gen3Auth uses the workspace\'s own login.',
    '#  - Anywhere else, set VECTIS_TOKEN to a short-lived access token first (os.environ["VECTIS_TOKEN"] = ...).',
    'import os',
    'import pandas as pd',
    'import requests',
    '',
    `ENDPOINT = ${quoted(o.endpoint)}`,
    `INDEXES = ${pythonLiteral(indexes)}`,
    `COLUMNS = ${pythonLiteral(columns)}  # asked of every index; the service returns all columns and these are kept`,
    `OUTPUT_COLUMNS = ${pythonLiteral(wanted.length ? wanted : [...columns, 'index_name'])}`,
    `SORT_FIELD, SORT_ASCENDING = ${sortField === null ? 'None' : quoted(sortField)}, ${sortAsc ? 'True' : 'False'}`,
    `PAGE_SIZE = ${o.pageSize}`,
    `MAX_PAGES = ${o.maxPages}  # per index; a safety limit, raise it if you need more rows`,
    '',
    '# The time window and your filters, in the Guppy filter format the service reads.',
    `FILTER = ${pythonLiteral(filter)}`,
    '',
    'token = os.environ.get("VECTIS_TOKEN")',
    'if token:',
    '    auth, headers = None, {"Authorization": f"Bearer {token}"}',
    'else:',
    '    from gen3.auth import Gen3Auth',
    '    auth, headers = Gen3Auth(endpoint=ENDPOINT), {}',
    '',
    'def page_query(index, offset):',
    '    fields = " ".join(COLUMNS)',
    '    return f"query ($filter: JSON) {{ {index}(filter: $filter, first: {PAGE_SIZE}, offset: {offset}) {{ {fields} }} }}"',
    '',
    'rows = []',
    'for index in INDEXES:',
    '    for page in range(MAX_PAGES):',
    '        body = {"query": page_query(index, page * PAGE_SIZE), "variables": {"filter": FILTER}}',
    `        resp = requests.post(f"{ENDPOINT}${o.apiPath}", json=body, headers=headers, auth=auth, timeout=120)`,
    '        resp.raise_for_status()',
    '        payload = resp.json()',
    '        if payload.get("errors"):',
    '            raise RuntimeError(payload["errors"])',
    '        batch = (payload.get("data") or {}).get(index) or []',
    '        rows.extend({**row, "index_name": index} for row in batch)',
    '        if len(batch) < PAGE_SIZE:',
    '            break',
    '',
    'if not rows:',
    '    print("No rows came back. Check you are signed in, that the window has data, and the column and filter names.")',
    'df = pd.DataFrame(rows)',
    'missing = [c for c in OUTPUT_COLUMNS if c not in df.columns]',
    'if rows and missing:',
    '    print("Columns the service did not return:", missing)',
    'df = df[[c for c in OUTPUT_COLUMNS if c in df.columns]]  # the service returns every column; keep the ones you chose',
    'if SORT_FIELD in df.columns:',
    '    df = df.sort_values(SORT_FIELD, ascending=SORT_ASCENDING).reset_index(drop=True)',
    'df.head()',
    '',
  ].join('\n');
}
